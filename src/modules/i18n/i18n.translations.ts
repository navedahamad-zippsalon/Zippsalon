export const languageFromDatabase = (language: string | null | undefined): SupportedLanguage => {
    if (language === "hi_en") return "hi-en";
    return isSupportedLanguage(language) ? language : "en";
};

export const languageToDatabase = (language: SupportedLanguage): "en" | "hi" | "hi_en" =>
    language === "hi-en" ? "hi_en" : language;

export const isSupportedLanguage = (value: unknown): value is SupportedLanguage =>
    typeof value === "string" && supportedLanguages.some(({ code }) => code === value);

export const translate = (
    language: SupportedLanguage,
    key: string,
    fallback?: string,
    variables?: TranslationVariables,
): string => {
    if (!translations[language][key]) reportMissingTranslation(language, key);
    const text = translations[language][key]
        ?? (language === "hi-en" ? key : translations.en[key] ?? fallback ?? key);
    return interpolate(text, variables);
};

const missingTranslationWarnings = new Set<string>();
const runtimeMissingTranslations: Record<SupportedLanguage, Set<string>> = {
    en: new Set(),
    hi: new Set(),
    "hi-en": new Set(),
};
const reportMissingTranslation = (language: SupportedLanguage, key: string): void => {
    const warningKey = `${language}:${key}`;
    runtimeMissingTranslations[language].add(key);
    if (missingTranslationWarnings.has(warningKey)) return;
    missingTranslationWarnings.add(warningKey);
    logger.warn("missing_translation", { language, key });
};

const interpolate = (message: string, variables: TranslationVariables = {}): string =>
    message.replace(/\{\{([a-zA-Z0-9_.-]+)\}\}/g, (placeholder, name: string) =>
        Object.prototype.hasOwnProperty.call(variables, name) && variables[name] !== undefined && variables[name] !== null
            ? String(variables[name])
            : placeholder,
    );

export const translationService = {
    translate(key: string, language: SupportedLanguage, variables?: TranslationVariables, fallback?: string): string {
        if (!translations[language][key]) {
            reportMissingTranslation(language, key);
        }
        return translate(language, key, fallback, variables);
    },
    translatePlural(key: string, count: number, language: SupportedLanguage, variables: TranslationVariables = {}): string {
        const form = count === 1 ? "one" : "other";
        return translate(language, `${key}.${form}`, undefined, { ...variables, count });
    },
};

export const getMissingTranslations = (): Record<SupportedLanguage, string[]> => {
    const keys = new Set(Object.values(translations).flatMap((catalog) => Object.keys(catalog)));
    const result = {} as Record<SupportedLanguage, string[]>;
    for (const code of Object.keys(translations) as SupportedLanguage[]) {
        result[code] = [...keys].filter((key) => !translations[code][key]);
    }
    return result;
};

export const getTranslationCoverage = (): Record<SupportedLanguage, number> => {
    const keys = new Set(Object.values(translations).flatMap((catalog) => Object.keys(catalog)));
    const total = keys.size;
    return Object.fromEntries(
        (Object.keys(translations) as SupportedLanguage[]).map((language) => [
            language,
            total === 0 ? 100 : Math.round((Object.keys(translations[language]).length / total) * 10000) / 100,
        ]),
    ) as Record<SupportedLanguage, number>;
};

export const getTranslationReport = () => {
    const keys = new Set(Object.values(translations).flatMap((catalog) => Object.keys(catalog)));
    const missing = getMissingTranslations();
    return {
        totalKeys: keys.size,
        runtimeMissing: Object.fromEntries(
            (Object.keys(runtimeMissingTranslations) as SupportedLanguage[]).map((language) => [
                language,
                [...runtimeMissingTranslations[language]].sort(),
            ]),
        ) as Record<SupportedLanguage, string[]>,
        languages: Object.fromEntries(
            (Object.keys(translations) as SupportedLanguage[]).map((language) => {
                const translated = keys.size - missing[language].length;
                return [language, {
                    translated,
                    missing: missing[language],
                    coverage: keys.size === 0 ? 100 : Math.round((translated / keys.size) * 10000) / 100,
                }];
            }),
        ) as Record<SupportedLanguage, { translated: number; missing: string[]; coverage: number }>,
    };
};

export const menuTranslationKey = (label: string): string => {
    const slug = label
        .normalize("NFKD")
        .replace(/&/g, " ")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "_")
        .replace(/^_+|_+$/g, "");
    return `navigation.${slug}`;
};

export const addMenuTranslations = <T extends { label?: unknown; children?: unknown }>(
    menu: T,
    language: SupportedLanguage,
): T & { key?: string; translationKey?: string; localizedLabel?: string; children?: unknown } => {
    if (typeof menu.label !== "string") return menu;
    const translationKey = menuTranslationKey(menu.label);
    const t = createTranslator(language);
    const children = Array.isArray(menu.children)
        ? menu.children.map((child) =>
            child && typeof child === "object"
                ? addMenuTranslations(child as { label?: unknown; children?: unknown }, language)
                : child,
        )
        : menu.children;
    const menuKey = translationKey.slice("navigation.".length);
    const existingKey = (menu as { key?: unknown }).key;
    return {
        ...menu,
        key: typeof existingKey === "string" ? existingKey : menuKey,
        translationKey,
        localizedLabel: t(translationKey),
        ...(Array.isArray(menu.children) ? { children } : {}),
    };
};

export const createTranslator = (
    language: SupportedLanguage,
    _isDevelopment = process.env.NODE_ENV === "development",
): TranslationFunction => (key, fallback, variables) => {
    if (!translations[language][key]) reportMissingTranslation(language, key);
    return translate(language, key, fallback, variables);
};
